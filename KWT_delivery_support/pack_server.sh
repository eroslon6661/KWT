#!/usr/bin/env bash
# Assemble the local handoff archive from the server's saved project and reports.
set -euo pipefail
export LC_ALL=C
umask 077

desktop=$(cd -- "$HOME/Desktop" && pwd -P)
support="$desktop/KWT_delivery_support.tar.gz"
output="$desktop/KWT_delivery.tar.gz"
stage=$(mktemp -d "$desktop/.kwt_delivery.XXXXXXXX")
trap 'rm -rf -- "$stage"' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
bundle="$stage/KWT_delivery"
src="$desktop/10_inputdata_verify/kwt_tcm_batch10"
run_rel="runs/batch10_pQxg9vhM"
run="$src/$run_rel"
[[ ! -e "$output" && ! -L "$output" ]] || {
    printf 'Output already exists: %s\n' "$output" >&2
    exit 1
}

for path in "$support" "$desktop/last_RTL.tar.gz" "$src/run_vcs.sh" \
    "$src/firmware/main.c" "$src/accel_rtl/kwt_accel_icb.v"; do
    [[ -f "$path" ]] || { printf 'Missing file: %s\n' "$path" >&2; exit 1; }
done
for name in matrix_array_8x8_dc_and_fm_rtl kwt_accel_icb_dc; do
    [[ -d "$desktop/$name" ]] || { printf 'Missing directory: %s/%s\n' "$desktop" "$name" >&2; exit 1; }
done

tar -xzf "$support" -C "$stage"
sup="$stage/kwt_delivery_support"
(cd "$sup" && sha256sum --quiet -c SHA256SUMS)
mkdir -p "$bundle"/{01_RTL,02_firmware,03_verification,04_synthesis,05_numerics}
cp -- "$sup/README_CN.md" "$bundle/"
cp -- "$desktop/last_RTL.tar.gz" "$bundle/01_RTL/"
cp -- "$sup/VCS_DESIGN_SHA256SUMS" "$bundle/01_RTL/"
cp -a -- "$src/firmware" "$src/build_firmware.sh" "$bundle/02_firmware/"
cp -a -- "$sup/numerics/." "$bundle/05_numerics/"
cp -a -- "$sup/evidence" "$bundle/03_verification/"
cp -- "$sup/kwt_vcs_module_verify_vcs.tar.gz" "$sup/kwt_sfu_verify_20261110.tar.gz" \
    "$bundle/03_verification/"
cp -- "$sup/dc_review.pdf" "$bundle/04_synthesis/"
if [[ -f "$desktop/kwt_e203_offline/env.sh" ]]; then
    cp -- "$desktop/kwt_e203_offline/env.sh" "$bundle/02_firmware/env_server_snapshot.sh"
fi

audit="$bundle/01_RTL/source_audit.txt"
printf 'Recorded project: %s\n' "$src" > "$audit"
if (cd "$src" && sha256sum -c "$sup/VCS_DESIGN_SHA256SUMS") >> "$audit" 2>&1; then
    printf 'VCS_DESIGN_MATCH=PASS\n' | tee -a "$audit"
else
    printf 'VCS_DESIGN_MATCH=DIFF_OR_MISSING; see 01_RTL/source_audit.txt\n' | tee -a "$audit"
fi
archive_ok=1
while read -r expected file; do
    member=$(tar -xOzf "$desktop/last_RTL.tar.gz" "$file" | sha256sum) || { archive_ok=0; continue; }
    if [[ "${member%% *}" != "$expected" ]]; then
        printf 'last_RTL.tar.gz: DIFF %s\n' "$file" >> "$audit"
        archive_ok=0
    fi
done < "$sup/VCS_DESIGN_SHA256SUMS"
if (( archive_ok )); then
    printf 'LAST_RTL_MATCH=PASS\n' | tee -a "$audit"
else
    printf 'LAST_RTL_MATCH=DIFF_OR_MISSING; see 01_RTL/source_audit.txt\n' | tee -a "$audit"
fi

project="$bundle/03_verification/kwt_tcm_batch10"
mkdir -p "$project"
(cd "$src" && tar -cf - --exclude=./runs --exclude='__pycache__' --exclude='*.pyc' .) |
    (cd "$project" && tar -xf -)

if [[ -d "$run" ]]; then
    dest="$project/$run_rel"
    mkdir -p "$dest"
    # Simulators and their temporary objects are regenerated by run_vcs.sh.
    (cd "$run" && tar -cf - --exclude='simv' --exclude='simv.daidir' \
        --exclude='csrc' --exclude='*.vcd' --exclude='*.vpd' --exclude='*.fsdb' \
        --exclude='stdcell' --exclude='sram' .) | (cd "$dest" && tar -xf -)
    for file in numerical.json execution.json layer_12_ln2.hex; do
        count=$(find "$dest/cases" -mindepth 2 -maxdepth 2 -type f -name "$file" -print 2>/dev/null | wc -l) || true
        printf 'BATCH10 %s %s/10\n' "$file" "$count" | tee -a "$audit"
    done
else
    printf 'BATCH10 original run directory missing: %s\n' "$run" | tee -a "$audit"
fi

if [[ -f "$desktop/dashboard.html" ]]; then
    cp -- "$desktop/dashboard.html" "$bundle/03_verification/evidence/"
    for candidate in "$HOME"/kwt_cov_matrix_data.*/urg/dashboard.html; do
        if [[ -f "$candidate" ]] && cmp -s "$candidate" "$desktop/dashboard.html"; then
            cp -a -- "$(dirname -- "$candidate")" "$bundle/03_verification/evidence/urg"
            break
        fi
    done
fi

synth="$bundle/04_synthesis"
for name in matrix_array_8x8_dc_and_fm_rtl kwt_accel_icb_dc; do
    # Preserve the relative layout for RTL, netlists, constraints, and reports.
    (
        cd "$desktop"
        find -H "$name" \( -name '.git' -o -name 'lib' -o -name 'libs' -o -name 'libraries' -o -name 'csrc' \) -prune -o \
            -type f \( -iname '*.rpt*' -o -iname '*.log*' -o -iname '*.v' -o -iname '*.sv' \
                -o -iname '*.report' -o -iname '*.qor' -o -iname '*.area' -o -iname '*.tim' \
                -o -iname '*.vh' -o -iname '*.svh' -o -iname '*.f' -o -iname '*.tcl' -o -iname '*.sdc' \
                -o -iname '*.ddc' -o -iname '*.sdf' -o -iname '*.svf' \
                -o -iname '*.txt' -o -iname '*.md' -o -iname '*.json' -o -iname '*.html' \
                -o -iname '*.pdf' -o -iname '*.docx' -o -iname '*.png' -o -iname '*.jpg' \
                -o -iname '*.csv' -o -iname '*.sh' -o -iname '*.out' \) \
            -exec cp --parents -p -t "$synth" -- {} +
    )
    if [[ -d "$synth/$name" ]]; then
        printf 'SYNTH %s saved_files=%s\n' "$name" "$(find "$synth/$name" -type f | wc -l)" | tee -a "$audit"
    else
        printf 'SYNTH %s has no recognized report or source files\n' "$name" | tee -a "$audit"
    fi
done

(
    cd "$bundle"
    find . -type f ! -path './SHA256SUMS' -print0 | sort -z | xargs -0 sha256sum > SHA256SUMS
    sha256sum --quiet -c SHA256SUMS
)
tar -czf "$stage/KWT_delivery.tar.gz" -C "$stage" KWT_delivery
tar -tzf "$stage/KWT_delivery.tar.gz" >/dev/null
ln -T -- "$stage/KWT_delivery.tar.gz" "$output"
printf 'SAVED: %s\n' "$output"
ls -lh -- "$output"
sha256sum -- "$output"
